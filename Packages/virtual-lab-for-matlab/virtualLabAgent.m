function agent = virtualLabAgent(title, expertise, goal, role, model)
%virtualLabAgent Create a Virtual Lab agent definition.
arguments
    title (1,1) string
    expertise (1,1) string
    goal (1,1) string
    role (1,1) string
    model (1,1) string = "gpt-5-mini"
end

agent = struct( ...
    "Title", title, ...
    "Expertise", expertise, ...
    "Goal", goal, ...
    "Role", role, ...
    "Model", model, ...
    "SystemPrompt", buildSystemPrompt(title, expertise, goal, role));
end

function prompt = buildSystemPrompt(title, expertise, goal, role)
prompt = "You are a " + title + ". " + ...
    "Your expertise is in " + expertise + ". " + ...
    "Your goal is to " + goal + ". " + ...
    "Your role is to " + role + ". " + ...
    "Keep your responses concise and decision-oriented. " + ...
    "Do not restate the full agenda or repeat prior points unless needed to make a decision. " + ...
    "Prefer short paragraphs or compact bullet lists over long exposition.";
end
