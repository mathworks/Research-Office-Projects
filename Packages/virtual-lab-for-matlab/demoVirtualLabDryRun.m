scriptDir = fileparts(mfilename("fullpath"));
addpath(scriptDir);

principalInvestigator = virtualLabAgent( ...
    "Principal Investigator", ...
    "running interdisciplinary scientific research programs", ...
    "lead a research team toward a concrete project decision", ...
    "convene the discussion, synthesize disagreements, and choose the next step", ...
    "gpt-5-mini");

immunologist = virtualLabAgent( ...
    "Immunologist", ...
    "antibody engineering and immune response characterization", ...
    "identify biologically credible nanobody directions", ...
    "advise on binding breadth, specificity, and experimental plausibility", ...
    "gpt-5-mini");

machineLearningSpecialist = virtualLabAgent( ...
    "Machine Learning Specialist", ...
    "protein modeling and candidate ranking workflows", ...
    "identify computational approaches that reduce experimental search", ...
    "propose models, ranking strategies, and validation loops", ...
    "gpt-5-mini");

scientificCritic = virtualLabAgent( ...
    "Scientific Critic", ...
    "stress-testing scientific plans for rigor and feasibility", ...
    "identify weak assumptions before implementation", ...
    "challenge unsupported claims and demand sharper decisions", ...
    "gpt-5-mini");

agenda = "Design a nanobody-discovery workflow for a new SARS-CoV-2 variant and decide whether the initial effort should focus on modifying known binders or proposing de novo candidates.";
agendaQuestions = [ ...
    "Should the project start from known nanobody scaffolds or from de novo design?", ...
    "Which computational tools should be in the first implementation slice?", ...
    "What evidence would justify advancing a candidate to wet-lab review?"];

[summary, discussion, meta] = runVirtualMeeting("team", agenda, ...
    SaveDir=fullfile(scriptDir, "output"), ...
    SaveName="dry_run_team_meeting", ...
    TeamLead=principalInvestigator, ...
    TeamMembers=[immunologist, machineLearningSpecialist, scientificCritic], ...
    AgendaQuestions=agendaQuestions, ...
    NumRounds=2, ...
    UseSDK=false, ...
    DryRun=true);

disp("Summary:")
disp(summary)
disp("Turns:")
disp(numel(discussion))
disp("Saved JSON:")
disp(meta.JsonPath)
