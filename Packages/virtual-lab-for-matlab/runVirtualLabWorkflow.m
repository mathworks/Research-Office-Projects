function namedAgents = indexAgents(agentArray)
namedAgents = struct();
for idx = 1:numel(agentArray)
    fieldName = matlab.lang.makeValidName(erase(agentArray(idx).Title, " "));
    namedAgents.(fieldName) = agentArray(idx);
end
end

function teamMembers = agentsFromNames(agents, names)
teamMembers = repmat(agents.(names(1)), 1, numel(names));
for idx = 1:numel(names)
    teamMembers(idx) = agents.(names(idx));
end
end

function listText = formatPromptList(items)
parts = strings(1, numel(items));
for idx = 1:numel(items)
    parts(idx) = string(idx) + ". " + items(idx);
end
listText = join(parts, newline + newline);
listText = join(string(listText), "");
listText = listText(1);
end

function event = enrichWorkflowEvent(event, phaseIndex, phaseName, iterationIndex, isMerge)
event.PhaseIndex = phaseIndex;
event.PhaseName = string(phaseName);
event.IterationIndex = iterationIndex;
event.IsMerge = isMerge;
end

function emitEvent(callback, event)
if isempty(callback)
    return
end

try
    callback(event);
catch ME
    warning("runVirtualLabWorkflow:EventCallbackFailed", ...
        "Event callback failed: %s", ME.message);
end

drawnow limitrate
end

function tf = shouldCancel(callback)
if isempty(callback)
    tf = false;
    return
end

try
    tf = logical(callback());
catch
    tf = false;
end
end

function out = ternary(condition, trueValue, falseValue)
if condition
    out = trueValue;
else
    out = falseValue;
end
end

function phases = resolveWorkflowPhases(projectBrief, phases)
projectBriefToken = "{{PROJECT_BRIEF}}";
for idx = 1:numel(phases)
    phases(idx).Agenda = replace(string(phases(idx).Agenda), projectBriefToken, projectBrief);
    phases(idx).AgendaQuestions = replace(string(phases(idx).AgendaQuestions), projectBriefToken, projectBrief);
    phases(idx).AgendaRules = replace(string(phases(idx).AgendaRules), projectBriefToken, projectBrief);
    phases(idx).Contexts = replace(string(phases(idx).Contexts), projectBriefToken, projectBrief);
end
end
