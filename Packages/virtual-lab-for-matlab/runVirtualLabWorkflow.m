function results = runVirtualLabWorkflow(projectBrief, nvp)
%runVirtualLabWorkflow Run a multi-phase Virtual Lab workflow.
arguments
    projectBrief (1,1) string
    nvp.SaveRoot (1,1) string = "workflow_output"
    nvp.NumIterations (1,1) double {mustBePositive, mustBeInteger} = 3
    nvp.NumRounds (1,1) double {mustBeNonnegative, mustBeInteger} = 2
    nvp.UseSDK (1,1) logical = true
    nvp.DryRun (1,1) logical = false
    nvp.Provider (1,1) string = "openai"
    nvp.BaseURL (1,1) string = ""
    nvp.Client = []
    nvp.Tools = []
    nvp.Workspace (1,1) struct = struct()
    nvp.Temperature = 0.2
    nvp.DisplayMode (1,1) string {mustBeMember(nvp.DisplayMode, ["off", "detailed"])} = "off"
    nvp.MaxIterations (1,1) double {mustBePositive, mustBeInteger} = 25
    nvp.Agents (1,:) struct = defaultWorkflowAgents()
    nvp.Phases (1,:) struct = struct.empty(1,0)
    nvp.OnEvent = []
    nvp.TurnPauseSeconds (1,1) double {mustBeNonnegative} = 0
    nvp.ShouldCancel = []
end

saveRoot = char(nvp.SaveRoot);
if ~exist(saveRoot, "dir")
    mkdir(saveRoot);
end

agents = indexAgents(nvp.Agents);
if isempty(nvp.Phases)
    phases = defaultWorkflowPhaseConfigs();
else
    phases = nvp.Phases;
end
phases = resolveWorkflowPhases(projectBrief, phases);

iterationResultTemplate = struct( ...
    "Summary", "", ...
    "Discussion", struct("agent", string.empty(1,0), "message", string.empty(1,0)), ...
    "Meta", struct());
phaseResultTemplate = struct( ...
    "Name", "", ...
    "Agenda", "", ...
    "IterationSummaries", strings(1,0), ...
    "MergedSummary", "", ...
    "IterationResults", iterationResultTemplate, ...
    "MergedDiscussion", struct("agent", string.empty(1,0), "message", string.empty(1,0)), ...
    "MergedMeta", struct());

results = struct( ...
    "ProjectBrief", projectBrief, ...
    "PhaseResults", repmat(phaseResultTemplate, 1, numel(phases)), ...
    "SaveRoot", string(saveRoot));

emitEvent(nvp.OnEvent, struct( ...
    "Type", "workflow_started", ...
    "ProjectBrief", projectBrief, ...
    "SaveRoot", string(saveRoot), ...
    "NumIterations", nvp.NumIterations, ...
    "PhaseNames", string({phases.Name})));

previousMergedSummaries = strings(1, numel(phases));
mergedSummaryCount = 0;
completedPhaseCount = 0;
cancelled = false;

for phaseIndex = 1:numel(phases)
    if shouldCancel(nvp.ShouldCancel)
        cancelled = true;
        break
    end
    phase = phases(phaseIndex);
    phaseDir = fullfile(saveRoot, phase.Name);
    if ~exist(phaseDir, "dir")
        mkdir(phaseDir);
    end

    emitEvent(nvp.OnEvent, struct( ...
        "Type", "phase_started", ...
        "PhaseIndex", phaseIndex, ...
        "PhaseName", phase.Name, ...
        "Agenda", phase.Agenda, ...
        "NumIterations", nvp.NumIterations));

    iterationSummaries = strings(1, nvp.NumIterations);
    iterationResults = repmat(iterationResultTemplate, 1, nvp.NumIterations);
    mergedSummary = "";
    mergedDiscussion = struct("agent", string.empty(1,0), "message", string.empty(1,0));
    mergedMeta = struct();
    completedIterations = 0;
    for iterationIndex = 1:nvp.NumIterations
        if shouldCancel(nvp.ShouldCancel)
            cancelled = true;
            break
        end
        emitEvent(nvp.OnEvent, struct( ...
            "Type", "phase_iteration_started", ...
            "PhaseIndex", phaseIndex, ...
            "PhaseName", phase.Name, ...
            "IterationIndex", iterationIndex));

        meetingEventCallback = @(event) emitEvent(nvp.OnEvent, enrichWorkflowEvent(event, phaseIndex, phase.Name, iterationIndex, false));
        runArgs = baseRunArgs(nvp, phaseDir, "discussion_" + string(iterationIndex), previousMergedSummaries(1:mergedSummaryCount), meetingEventCallback);
        [summary, discussion, meta] = runPhaseMeeting(phase, agents, runArgs);
        iterationSummaries(iterationIndex) = summary;
        iterationResults(iterationIndex) = struct( ...
            "Summary", summary, ...
            "Discussion", discussion, ...
            "Meta", meta);
        completedIterations = iterationIndex;

        emitEvent(nvp.OnEvent, struct( ...
            "Type", "phase_iteration_completed", ...
            "PhaseIndex", phaseIndex, ...
            "PhaseName", phase.Name, ...
            "IterationIndex", iterationIndex, ...
            "Summary", summary, ...
            "Meta", meta));
    end

    if cancelled
        results.PhaseResults(phaseIndex) = struct( ...
            "Name", phase.Name, ...
            "Agenda", phase.Agenda, ...
            "IterationSummaries", iterationSummaries(1:completedIterations), ...
            "MergedSummary", mergedSummary, ...
            "IterationResults", iterationResults(1:max(completedIterations,1)), ...
            "MergedDiscussion", mergedDiscussion, ...
            "MergedMeta", mergedMeta);
        completedPhaseCount = phaseIndex;
        break
    end

    mergeAgenda = createMergeAgenda(phase);
    mergeEventCallback = @(event) emitEvent(nvp.OnEvent, enrichWorkflowEvent(event, phaseIndex, phase.Name, 0, true));
    mergeArgs = baseRunArgs(nvp, phaseDir, "merged", iterationSummaries(1:completedIterations), mergeEventCallback);
    mergePhase = phase;
    mergePhase.MeetingType = "individual";
    mergePhase.TeamMember = "PrincipalInvestigator";
    mergePhase.TeamMembers = strings(1, 0);
    [mergedSummary, mergedDiscussion, mergedMeta] = runPhaseMeeting(mergePhase, agents, mergeArgs, mergeAgenda);

    results.PhaseResults(phaseIndex) = struct( ...
        "Name", phase.Name, ...
        "Agenda", phase.Agenda, ...
        "IterationSummaries", iterationSummaries, ...
        "MergedSummary", mergedSummary, ...
        "IterationResults", iterationResults, ...
        "MergedDiscussion", mergedDiscussion, ...
        "MergedMeta", mergedMeta);
    completedPhaseCount = phaseIndex;

    mergedSummaryCount = mergedSummaryCount + 1;
    previousMergedSummaries(mergedSummaryCount) = mergedSummary;
    emitEvent(nvp.OnEvent, struct( ...
        "Type", "phase_merged", ...
        "PhaseIndex", phaseIndex, ...
        "PhaseName", phase.Name, ...
        "MergedSummary", mergedSummary, ...
        "MergedMeta", mergedMeta));
end

if completedPhaseCount > 0
    results.PhaseResults = results.PhaseResults(1:completedPhaseCount);
else
    results.PhaseResults = results.PhaseResults([]);
end

results.Status = ternary(cancelled, "cancelled", "completed");

if cancelled
    emitEvent(nvp.OnEvent, struct( ...
        "Type", "workflow_cancelled", ...
        "ProjectBrief", projectBrief, ...
        "Results", results));
else
    emitEvent(nvp.OnEvent, struct( ...
        "Type", "workflow_completed", ...
        "ProjectBrief", projectBrief, ...
        "Results", results));
end
end

function runArgs = baseRunArgs(nvp, saveDir, saveName, summaries, onEvent)
runArgs = struct( ...
    "SaveDir", string(saveDir), ...
    "SaveName", string(saveName), ...
    "AgendaQuestions", strings(1, 0), ...
    "AgendaRules", strings(1, 0), ...
    "Summaries", summaries, ...
    "Contexts", strings(1, 0), ...
    "NumRounds", nvp.NumRounds, ...
    "UseSDK", nvp.UseSDK, ...
    "DryRun", nvp.DryRun, ...
    "Provider", nvp.Provider, ...
    "BaseURL", nvp.BaseURL, ...
    "Client", nvp.Client, ...
    "Tools", nvp.Tools, ...
    "Workspace", nvp.Workspace, ...
    "Temperature", nvp.Temperature, ...
    "DisplayMode", nvp.DisplayMode, ...
    "MaxIterations", nvp.MaxIterations, ...
    "OnEvent", onEvent, ...
    "TurnPauseSeconds", nvp.TurnPauseSeconds, ...
    "ShouldCancel", nvp.ShouldCancel);
end

function [summary, discussion, meta] = runPhaseMeeting(phase, agents, runArgs, overrideAgenda)
if nargin < 4
    agenda = phase.Agenda;
else
    agenda = overrideAgenda;
end

runArgs.AgendaQuestions = phase.AgendaQuestions;
runArgs.AgendaRules = phase.AgendaRules;
runArgs.Contexts = phase.Contexts;

if phase.MeetingType == "team"
    [summary, discussion, meta] = runVirtualMeeting("team", agenda, ...
        SaveDir=runArgs.SaveDir, ...
        SaveName=runArgs.SaveName, ...
        TeamLead=agents.(phase.TeamLead), ...
        TeamMembers=agentsFromNames(agents, phase.TeamMembers), ...
        TeamMemberOrder=phase.TeamMemberOrder, ...
        AgendaQuestions=runArgs.AgendaQuestions, ...
        AgendaRules=runArgs.AgendaRules, ...
        Summaries=runArgs.Summaries, ...
        Contexts=runArgs.Contexts, ...
        NumRounds=runArgs.NumRounds, ...
        UseSDK=runArgs.UseSDK, ...
        DryRun=runArgs.DryRun, ...
        Provider=runArgs.Provider, ...
        BaseURL=runArgs.BaseURL, ...
        Client=runArgs.Client, ...
        Tools=runArgs.Tools, ...
        Workspace=runArgs.Workspace, ...
        Temperature=runArgs.Temperature, ...
        DisplayMode=runArgs.DisplayMode, ...
        MaxIterations=runArgs.MaxIterations, ...
        OnEvent=runArgs.OnEvent, ...
        TurnPauseSeconds=runArgs.TurnPauseSeconds, ...
        ShouldCancel=runArgs.ShouldCancel);
else
    [summary, discussion, meta] = runVirtualMeeting("individual", agenda, ...
        SaveDir=runArgs.SaveDir, ...
        SaveName=runArgs.SaveName, ...
        TeamMember=agents.(phase.TeamMember), ...
        AgendaQuestions=runArgs.AgendaQuestions, ...
        AgendaRules=runArgs.AgendaRules, ...
        Summaries=runArgs.Summaries, ...
        Contexts=runArgs.Contexts, ...
        NumRounds=runArgs.NumRounds, ...
        UseSDK=runArgs.UseSDK, ...
        DryRun=runArgs.DryRun, ...
        Provider=runArgs.Provider, ...
        BaseURL=runArgs.BaseURL, ...
        Client=runArgs.Client, ...
        Tools=runArgs.Tools, ...
        Workspace=runArgs.Workspace, ...
        Temperature=runArgs.Temperature, ...
        DisplayMode=runArgs.DisplayMode, ...
        MaxIterations=runArgs.MaxIterations, ...
        OnEvent=runArgs.OnEvent, ...
        TurnPauseSeconds=runArgs.TurnPauseSeconds, ...
        ShouldCancel=runArgs.ShouldCancel);
end
end

function mergeAgenda = createMergeAgenda(phase)
parts = strings(1, 0);
parts(end+1) = "Please read the summaries of multiple separate meetings about the same agenda. " + ...
    "Based on the summaries, provide a single merged answer that keeps the strongest parts of each discussion." + ...
    newline + newline + ...
    "Original agenda:" + newline + newline + phase.Agenda + newline + newline;

if ~isempty(phase.AgendaQuestions)
    parts(end+1) = "Agenda questions:" + newline + newline + ...
        formatPromptList(phase.AgendaQuestions) + newline + newline;
end

if ~isempty(phase.AgendaRules)
    parts(end+1) = "Agenda rules:" + newline + newline + ...
        formatPromptList(phase.AgendaRules) + newline + newline;
end

mergeAgenda = join(parts, "");
mergeAgenda = mergeAgenda(1);
end

